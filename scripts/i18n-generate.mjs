/* eslint-env node, es2020 */
// Generates the language registry from the directories in locales/, so that
// adding a language needs nothing but locales/<code>/meta.json and the
// locales/<code>/<area>.json translation files:
// - locales/generated.ts: LANGUAGES (from meta.json), the SupportedLanguage
//   type, isSupportedLanguage() and the i18next resources built from every
//   area file
// - locales/generated-plurals.ts: the Intl.PluralRules polyfill data for
//   exactly the languages that exist
// Both files are committed; `yarn i18n:check` fails when they are stale.
// Run with `yarn i18n:generate`.
import {
  existsSync,
  readdirSync,
  readFileSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import prettier from "prettier";

export const rootDir = join(dirname(fileURLToPath(import.meta.url)), "..");
export const baseLanguage = "en";
// directory names are BCP-47 language tags in canonical form: "cs", "pt-BR"
export const languageCodePattern = /^[a-z]{2,3}(-[A-Za-z0-9]+)*$/;
// area file names become the top-level translation keys ("settings.title")
const areaNamePattern = /^[a-z][a-zA-Z0-9]*$/;
const pluralDataDir = "node_modules/@formatjs/intl-pluralrules/locale-data";
export const generatedFiles = {
  registry: "locales/generated.ts",
  plurals: "locales/generated-plurals.ts",
};
const header =
  "// GENERATED by scripts/i18n-generate.mjs — do not edit, run `yarn i18n:generate`";

export class I18nGenerateError extends Error {
  constructor(problems) {
    super(problems.join("\n"));
    this.name = "I18nGenerateError";
    this.problems = problems;
  }
}

function canonicalLocale(value) {
  try {
    return Intl.getCanonicalLocales(value)[0];
  } catch {
    return undefined;
  }
}

function languageOf(tag) {
  try {
    return new Intl.Locale(tag).language;
  } catch {
    return undefined;
  }
}

// Finds the @formatjs plural data for a language, falling back from the full
// tag to its language subtag ("pt-BR" -> "pt"); the polyfill resolves the
// region variants from the base language data.
export function resolvePluralData(code, root = rootDir) {
  const subtags = code.split("-");
  for (let length = subtags.length; length > 0; length--) {
    const candidate = subtags.slice(0, length).join("-");
    if (existsSync(join(root, pluralDataDir, `${candidate}.js`))) {
      return candidate;
    }
  }
  return undefined;
}

function readLanguage(code, languageDir, root) {
  const problems = [];
  const relativeMeta = `locales/${code}/meta.json`;

  if (!languageCodePattern.test(code)) {
    problems.push(
      `locales/${code}: directory name must be a BCP-47 language tag such as "cs" or "pt-BR"`,
    );
  } else if (canonicalLocale(code) !== code) {
    problems.push(
      `locales/${code}: directory name must be the canonical BCP-47 form ("${canonicalLocale(code) ?? "?"}")`,
    );
  }

  let meta;
  try {
    meta = JSON.parse(readFileSync(join(languageDir, "meta.json"), "utf8"));
  } catch (error) {
    problems.push(`${relativeMeta}: ${error.message}`);
    return { problems };
  }
  if (meta === null || typeof meta !== "object" || Array.isArray(meta)) {
    problems.push(`${relativeMeta}: must be an object`);
    return { problems };
  }
  if (typeof meta.name !== "string" || meta.name.trim() === "") {
    problems.push(
      `${relativeMeta}: "name" must be the language name in that language`,
    );
  }
  if (typeof meta.tag !== "string" || canonicalLocale(meta.tag) === undefined) {
    problems.push(
      `${relativeMeta}: "tag" must be a BCP-47 tag such as "cs-CZ"`,
    );
  } else if (languageOf(meta.tag) !== languageOf(code)) {
    problems.push(
      `${relativeMeta}: "tag" (${meta.tag}) must be a variant of the directory language "${code}"`,
    );
  }
  if (
    meta.weekStart !== undefined &&
    (!Number.isInteger(meta.weekStart) ||
      meta.weekStart < 0 ||
      meta.weekStart > 6)
  ) {
    problems.push(
      `${relativeMeta}: "weekStart" must be a day index from 0 (Sunday) to 6`,
    );
  }
  for (const key of Object.keys(meta)) {
    if (!["name", "tag", "weekStart"].includes(key)) {
      problems.push(`${relativeMeta}: unknown field "${key}"`);
    }
  }

  const areas = readdirSync(languageDir)
    .filter(
      (fileName) => fileName.endsWith(".json") && fileName !== "meta.json",
    )
    .map((fileName) => fileName.slice(0, -".json".length))
    .sort();
  for (const area of areas) {
    if (!areaNamePattern.test(area)) {
      problems.push(
        `locales/${code}/${area}.json: area file names must be camelCase identifiers`,
      );
    }
  }

  const pluralData = resolvePluralData(code, root);
  if (pluralData === undefined) {
    problems.push(
      `locales/${code}: no Intl.PluralRules data for "${code}" in @formatjs/intl-pluralrules/locale-data`,
    );
  }

  return {
    problems,
    language: {
      code,
      name: meta.name,
      tag: meta.tag,
      weekStart: meta.weekStart ?? 0,
      areas,
      pluralData,
    },
  };
}

// Reads every locales/<code>/ directory that has a meta.json. Directories
// without one are listed in `skipped` (locales/native is not a language);
// invalid directories are described in `problems`. Languages are ordered
// English first, then by code.
export function discoverLanguages(root = rootDir) {
  const localesDir = join(root, "locales");
  const languages = [];
  const skipped = [];
  const problems = [];
  for (const entry of readdirSync(localesDir).sort()) {
    const languageDir = join(localesDir, entry);
    if (entry === "native" || !statSync(languageDir).isDirectory()) {
      continue;
    }
    if (!existsSync(join(languageDir, "meta.json"))) {
      skipped.push(entry);
      continue;
    }
    const result = readLanguage(entry, languageDir, root);
    problems.push(...result.problems);
    if (result.language) {
      languages.push(result.language);
    }
  }
  languages.sort((a, b) => {
    if (a.code === baseLanguage || b.code === baseLanguage) {
      return a.code === baseLanguage ? -1 : 1;
    }
    return a.code < b.code ? -1 : 1;
  });
  return { languages, skipped, problems };
}

function capitalize(value) {
  return value.charAt(0).toUpperCase() + value.slice(1);
}

// "pt-BR" + "common" -> ptBRCommon
function importIdentifier(code, area) {
  const [first, ...rest] = code.split("-");
  return first + rest.map(capitalize).join("") + capitalize(area);
}

function renderRegistry(languages) {
  const imports = [...languages]
    .sort((a, b) => (a.code < b.code ? -1 : 1))
    .flatMap((language) =>
      language.areas.map(
        (area) =>
          `import ${importIdentifier(language.code, area)} from "./${language.code}/${area}.json";`,
      ),
    );
  const languageEntries = languages.map(
    (language) =>
      `  { code: ${JSON.stringify(language.code)}, name: ${JSON.stringify(language.name)}, tag: ${JSON.stringify(language.tag)}, weekStart: ${language.weekStart} },`,
  );
  const resourceEntries = languages.map((language) => {
    const areas = language.areas.map(
      (area) => `      ${area}: ${importIdentifier(language.code, area)},`,
    );
    return [
      `  ${JSON.stringify(language.code)}: {`,
      "    translation: {",
      ...areas,
      "    },",
      "  },",
    ].join("\n");
  });
  return [
    header,
    "// Source: locales/<code>/meta.json and locales/<code>/<area>.json",
    ...imports,
    "",
    "// Languages shipped with the app, English first, then by code.",
    "export const LANGUAGES = [",
    ...languageEntries,
    "] as const;",
    "",
    "export type LanguageMeta = (typeof LANGUAGES)[number];",
    'export type SupportedLanguage = LanguageMeta["code"];',
    "",
    "export function isSupportedLanguage(",
    "  value: unknown,",
    "): value is SupportedLanguage {",
    "  return LANGUAGES.some((language) => language.code === value);",
    "}",
    "",
    '// Every area file is merged into the single "translation" namespace with the',
    '// area name as the top-level key, e.g. t("settings.language.title").',
    "export const resources = {",
    ...resourceEntries,
    "};",
    "",
  ].join("\n");
}

function renderPlurals(languages) {
  const dataNames = [
    ...new Set(languages.map((language) => language.pluralData)),
  ].sort();
  return [
    header,
    "// Intl.PluralRules data for the languages in locales/, imported by",
    "// lib/applyGlobalPolyfills.ts after the polyfill itself.",
    ...dataNames.map(
      (name) => `import "@formatjs/intl-pluralrules/locale-data/${name}.js";`,
    ),
    "",
  ].join("\n");
}

async function formatWithPrettier(root, relativePath, content) {
  const filePath = join(root, relativePath);
  const options = await prettier.resolveConfig(filePath);
  return prettier.format(content, { ...options, filepath: filePath });
}

// Returns { [relativePath]: content } for the generated files, formatted with
// prettier, without touching the disk. Throws I18nGenerateError when a
// language directory is invalid.
export async function generateFiles(root = rootDir) {
  const { languages, problems } = discoverLanguages(root);
  if (problems.length > 0) {
    throw new I18nGenerateError(problems);
  }
  if (!languages.some((language) => language.code === baseLanguage)) {
    throw new I18nGenerateError([
      `locales/${baseLanguage}/meta.json is missing`,
    ]);
  }
  const files = {
    [generatedFiles.registry]: renderRegistry(languages),
    [generatedFiles.plurals]: renderPlurals(languages),
  };
  for (const [relativePath, content] of Object.entries(files)) {
    files[relativePath] = await formatWithPrettier(root, relativePath, content);
  }
  return files;
}

const isCli =
  process.argv[1] !== undefined &&
  resolve(process.argv[1]).toLowerCase() ===
    fileURLToPath(import.meta.url).toLowerCase();

if (isCli) {
  try {
    const { skipped } = discoverLanguages(rootDir);
    for (const code of skipped) {
      console.info(`Skipping locales/${code}: no meta.json`);
    }
    const files = await generateFiles(rootDir);
    for (const [relativePath, content] of Object.entries(files)) {
      const filePath = join(rootDir, relativePath);
      const existing = existsSync(filePath)
        ? readFileSync(filePath, "utf8")
        : null;
      if (existing === content) {
        console.info(`${relativePath} is up to date`);
      } else {
        writeFileSync(filePath, content);
        console.info(`Wrote ${relativePath}`);
      }
    }
  } catch (error) {
    for (const problem of error.problems ?? [error.message]) {
      console.error(`Error: ${problem}`);
    }
    process.exit(1);
  }
}
